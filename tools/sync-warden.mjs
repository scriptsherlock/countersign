// Writes the Warden engine from Trickbot into src/. Never edit the output: fix Trickbot, move the pin, re-sync.
// --check compares instead of writing, and fails if the vendored file has drifted.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { BEGIN, COMMIT, END, VENDOR, pinnedEngine } from './warden-source.mjs';

const output = `// Generated by tools/sync-warden.mjs. Do not edit: fix the engine in Trickbot, then re-sync.
// Source: scriptsherlock/trickbot index.html at commit ${COMMIT}
const module = { exports: {} };
${BEGIN}
${pinnedEngine()}${END}
export default module.exports;
`;

if (process.argv.includes('--check')) {
  if (!existsSync(VENDOR) || readFileSync(VENDOR, 'utf8') !== output) {
    console.error('The vendored Warden engine does not match the pinned commit. Run npm run sync:warden.');
    process.exit(1);
  }
  console.log(`Warden engine matches ${COMMIT.slice(0, 7)}.`);
} else {
  mkdirSync(dirname(VENDOR), { recursive: true });
  writeFileSync(VENDOR, output);
  console.log(`Synced the Warden engine from ${COMMIT.slice(0, 7)}.`);
}
